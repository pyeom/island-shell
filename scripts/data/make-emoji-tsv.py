"""Builds data/emoji.tsv from Unicode's emoji-test.txt.

    python3 -I scripts/data/make-emoji-tsv.py emoji-test.txt > data/emoji.tsv

Keeps fully-qualified emoji without skin-tone or hair variants. Columns:
emoji, name, group / subgroup (searched as keywords).
"""
import re
import sys

src = open(sys.argv[1], encoding="utf-8")
print("# Generated by scripts/data/make-emoji-tsv.py from Unicode emoji-test.txt.")
print("# Unicode data: © Unicode, Inc., https://www.unicode.org/license.txt")
group = subgroup = ""
for line in src:
    if line.startswith("# group:"):
        group = line.split(":", 1)[1].strip()
    elif line.startswith("# subgroup:"):
        subgroup = line.split(":", 1)[1].strip()
    m = re.match(r"^[0-9A-F ]+;\s*fully-qualified\s*#\s*(\S+)\s+(?:E\d+\.\d+\s+)?(.+)$", line)
    if not m:
        continue
    emoji, name = m.groups()
    if "skin tone" in name or "hair" in name and ":" in name:
        continue
    print(f"{emoji}\t{name.strip()}\t{group} {subgroup.replace('-', ' ')}")
